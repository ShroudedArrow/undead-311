// REQ-WEB-DATA.1: generate TypeScript types and CSP-safe ajv standalone validators from /schemas/*.schema.json.
// Usage: node scripts/gen-parsers.mjs          (writes src/lib/parse/generated/)
//        node scripts/gen-parsers.mjs --check  (exits 1 if the committed files are stale)
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, "..", "..", "schemas");
const outDir = join(here, "..", "src", "lib", "parse", "generated");

/** schema file stem -> exported type name. test_town_expected is the owner's answer key, not a web file. */
export const KINDS = {
  zombies: "ZombiesFile",
  card: "CardShard",
  points: "PointsFile",
  scorecard: "ScorecardFile",
  status: "StatusFile",
  judge_tour: "JudgeTourFile",
  validation: "ValidationFile",
  survival: "SurvivalFile",
  funnel: "FunnelFile",
  groups: "GroupsFile",
  excess: "ExcessFile",
  incidents: "IncidentsFile",
  exclusions: "ExclusionsFile",
  separate_deaths: "SeparateDeathsFile",
  repeat_offenders: "RepeatOffendersFile",
  bulk_closures: "BulkClosuresFile",
  temporary_fixes: "TemporaryFixesFile",
  sensitivity_grid: "SensitivityGridFile",
  trends: "TrendsFile",
  shard_index: "ShardIndexFile",
  districts: "DistrictsFile",
};

export function loadSchemas() {
  const out = {};
  for (const stem of Object.keys(KINDS)) {
    const path = join(schemaDir, `${stem}.schema.json`);
    if (!existsSync(path)) throw new Error(`missing schema ${path}`);
    out[stem] = JSON.parse(readFileSync(path, "utf8"));
  }
  return out;
}

export async function generate() {
  const schemas = loadSchemas();
  let types = "// Generated by scripts/gen-parsers.mjs from /schemas. Do not edit.\n/* eslint-disable */\n\n";
  for (const [stem, name] of Object.entries(KINDS)) {
    const schema = structuredClone(schemas[stem]);
    schema.title = name;
    types += await compile(schema, name, { bannerComment: "", additionalProperties: false, declareExternallyReferenced: true });
    types += "\n";
  }

  const out = { "types.ts": types };
  for (const [stem, schema] of Object.entries(schemas)) {
    // One module per schema, so a page bundles only the validators it imports.
    const ajv = new Ajv2020({ code: { source: true, esm: true }, strict: false, allErrors: false });
    const validate = ajv.compile(schema);
    let code = standaloneCode(ajv, validate);
    // Standalone code may `require` ajv's tiny runtime helpers; turn those into ESM imports so the bundle needs no eval.
    const helpers = [];
    code = code.replace(/const (\w+) = require\("([^"]+)"\)(\.default)?;?/g, (_m, id, mod) => {
      helpers.push(`import ${id}_mod from "${mod}";\nconst ${id} = (${id}_mod as any).default ?? ${id}_mod;`);
      return "";
    });
    out[`validators/${stem}.ts`] =
      `// Generated by scripts/gen-parsers.mjs (ajv standalone, no eval). Do not edit.\n// @ts-nocheck\n/* eslint-disable */\n${helpers.join("\n")}\n${code}\n`;
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = await generate();
  if (process.argv.includes("--check")) {
    let stale = false;
    for (const [name, text] of Object.entries(files)) {
      const p = join(outDir, name);
      if (!existsSync(p) || readFileSync(p, "utf8") !== text) {
        console.error(`stale: ${p}`);
        stale = true;
      }
    }
    process.exit(stale ? 1 : 0);
  }
  for (const [name, text] of Object.entries(files)) {
    mkdirSync(dirname(join(outDir, name)), { recursive: true });
    writeFileSync(join(outDir, name), text);
  }
  console.log(`wrote ${Object.keys(files).join(", ")} to ${outDir}`);
}
