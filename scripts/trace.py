"""`make trace`: build docs/TRACEABILITY.md, requirement ID -> code -> tests -> status. REQ-OPS-EVID.1.

Requirements come from the `### REQ-<id>: title` headings of .kiro/specs/*/requirements.md. Code and test files are
scanned for requirement IDs in docstrings, comments and test names (a cited sub-number such as `.2` counts for the requirement itself).

Status per requirement:
  tested      cited by code and by at least one test
  untested    cited by code, no test cites it
  test-only   cited by tests, no code cites it
  uncited     nothing cites it

Usage: python3 scripts/trace.py [--root .] [--out docs/TRACEABILITY.md]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HEADING = re.compile(r"^###\s+(REQ-[A-Z0-9]+(?:-[A-Z0-9]+)*):\s*(.+?)\s*$", re.M)
LAYER = re.compile(r"^\*\*Layer:\*\*\s*(\S+)", re.M)
CITE = re.compile(r"\bREQ-[A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*")

CODE_GLOBS = ["pipeline/undead311/**/*.py", "pipeline/scripts/*.py", "scripts/*.py", "ops/**/*.mjs", "ops/**/*.py", "ops/**/*.yml",
              "web/src/**/*.ts", "web/src/**/*.tsx", "web/scripts/*", ".github/workflows/*.yml", "Makefile", "netlify.toml"]
TEST_GLOBS = ["pipeline/tests/**/*.py", "web/src/**/*.test.ts", "web/src/**/*.test.tsx", "web/e2e/*.ts", "ops/**/test_*.py"]
SKIP_PARTS = {"node_modules", "__pycache__", "dist", ".venv", "generated"}
MAX_LISTED = 4


def _files(root: Path, globs: list[str]) -> set[Path]:
    out: set[Path] = set()
    for g in globs:
        for p in root.glob(g):
            if p.is_file() and not (SKIP_PARTS & set(p.relative_to(root).parts)):
                out.add(p)
    return out


def requirements(root: Path) -> dict[str, dict[str, str]]:
    """ID -> {title, layer, spec}, from every spec's requirements.md."""
    reqs: dict[str, dict[str, str]] = {}
    for f in sorted((root / ".kiro" / "specs").glob("*/requirements.md")):
        text = f.read_text(encoding="utf-8")
        marks = list(HEADING.finditer(text))
        for i, m in enumerate(marks):
            block = text[m.end(): marks[i + 1].start() if i + 1 < len(marks) else len(text)]
            layer = LAYER.search(block)
            reqs[m.group(1)] = {"title": m.group(2), "layer": layer.group(1) if layer else "", "spec": f.parent.name}
    return reqs


def citations(root: Path, files: set[Path]) -> dict[str, set[str]]:
    """Requirement ID (sub-number dropped) -> repo-relative files citing it."""
    out: dict[str, set[str]] = {}
    for f in files:
        try:
            text = f.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        for ident in set(CITE.findall(text)):
            out.setdefault(ident, set()).add(f.relative_to(root).as_posix())
    return out


def status(code: bool, tests: bool) -> str:
    if code and tests:
        return "tested"
    if code:
        return "untested"
    return "test-only" if tests else "uncited"


def _list(paths: set[str]) -> str:
    items = sorted(paths)
    shown = ", ".join(f"`{p}`" for p in items[:MAX_LISTED])
    return shown + (f" and {len(items) - MAX_LISTED} more" if len(items) > MAX_LISTED else "") if items else "none"


def build(root: Path) -> tuple[str, dict[str, str]]:
    """The markdown text and the status of every requirement."""
    reqs = requirements(root)
    test_files = _files(root, TEST_GLOBS)
    code_files = _files(root, CODE_GLOBS) - test_files
    in_code = citations(root, code_files)
    in_tests = citations(root, test_files)
    states = {rid: status(rid in in_code, rid in in_tests) for rid in reqs}
    counts = {s: sum(1 for v in states.values() if v == s) for s in ("tested", "untested", "test-only", "uncited")}
    out = [
        "# Traceability: requirement to code to tests",
        "",
        "Generated by `make trace` from the requirement headings in `.kiro/specs/*/requirements.md` and the requirement IDs",
        "cited in code docstrings, comments and test names. Do not edit by hand.",
        "",
        f"{len(reqs)} requirements: {counts['tested']} tested, {counts['untested']} cited by code only, "
        f"{counts['test-only']} cited by tests only, {counts['uncited']} not cited.",
        "",
        "| Requirement | Spec | Layer | Code | Tests | Status |",
        "|---|---|---|---|---|---|",
    ]
    for rid in sorted(reqs):
        r = reqs[rid]
        out.append(f"| {rid} {r['title']} | {r['spec']} | {r['layer'] or '-'} | {_list(in_code.get(rid, set()))} | "
                   f"{_list(in_tests.get(rid, set()))} | {states[rid]} |")
    unknown = sorted((set(in_code) | set(in_tests)) - set(reqs))
    if unknown:
        out += ["", "## IDs cited but not defined in any requirements.md", ""]
        out += [f"- {u}: {_list(in_code.get(u, set()) | in_tests.get(u, set()))}" for u in unknown]
    return "\n".join(out) + "\n", states


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=".")
    ap.add_argument("--out", default="docs/TRACEABILITY.md")
    args = ap.parse_args(argv)
    root = Path(args.root).resolve()
    text, states = build(root)
    out = Path(args.out) if Path(args.out).is_absolute() else root / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"trace: wrote {args.out} ({len(states)} requirements, {sum(v == 'tested' for v in states.values())} tested)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
