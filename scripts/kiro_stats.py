"""`make kiro-stats`: commits, files and tests per agent and per workflow run, from commit trailers. REQ-OPS-EVID.1.

Reads `Kiro-Agent` and `Kiro-Run` trailers (structure.md). Merge commits are not counted (a merge is not an agent's
change, same rule as scripts/check_trailers.py). Commits authored by the owner count under "owner" (reusing
check_trailers.is_owner). Any other commit without trailers counts under "(no trailer)", so a gap shows up.

  commits   non-merge commits
  files     distinct files the commits touched
  tests     test definitions added or changed (a renamed or moved test counts again): `def test_*` in Python test files, `it(` / `test(` in TypeScript tests

Usage: python3 scripts/kiro_stats.py [REV_RANGE] [--out docs/KIRO_STATS.md]    (default range: HEAD)
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_trailers import is_owner

NO_TRAILER = "(no trailer)"
OWNER = "owner"
RECORD = "\x1e"
FIELD = "\x1f"
TEST_FILE = re.compile(r"(^|/)(test_[^/]+\.py|[^/]+\.test\.tsx?|[^/]+\.spec\.ts)$")
TEST_PY = re.compile(r"^\+\s*(async\s+)?def test_\w+")
TEST_TS = re.compile(r"^\+\s*(it|test)(\.each\([^)]*\))?\(")
DIFF_HEADER = re.compile(r"^diff --git a/(.+?) b/(.+)$")


@dataclass
class Commit:
    sha: str
    name: str
    email: str
    agent: str
    run: str
    files: set[str] = field(default_factory=set)
    tests: int = 0


@dataclass
class Tally:
    commits: int = 0
    files: set[str] = field(default_factory=set)
    tests: int = 0


def count_tests(path: str, line: str) -> int:
    """1 when the added diff line starts a test in a test file, else 0."""
    if not TEST_FILE.search(path):
        return 0
    return int(bool(TEST_PY.match(line) if path.endswith(".py") else TEST_TS.match(line)))


def parse(log: str) -> list[Commit]:
    """Parse `git log --no-merges --no-renames -p -U0` output made with the record format in `read_log`."""
    commits: list[Commit] = []
    for rec in log.split(RECORD):
        if not rec.strip():
            continue
        head, _, diff = rec.partition("\n")
        parts = head.split(FIELD)
        if len(parts) < 5:
            continue
        sha, name, email, agent, run = (p.strip() for p in parts[:5])
        c = Commit(sha, name, email, agent, run)
        path = ""
        for line in diff.splitlines():
            m = DIFF_HEADER.match(line)
            if m:
                path = m.group(2)
                c.files.add(path)
            elif line.startswith("+") and not line.startswith("+++") and path:
                c.tests += count_tests(path, line)
        commits.append(c)
    return commits


def read_log(rev: str) -> str:
    fmt = RECORD + FIELD.join(["%H", "%an", "%ae", "%(trailers:key=Kiro-Agent,valueonly,unfold,separator=%x2c)",
                               "%(trailers:key=Kiro-Run,valueonly,unfold,separator=%x2c)"])
    return subprocess.run(["git", "log", "--no-merges", "--no-renames", "-p", "-U0", f"--format={fmt}", rev],
                          capture_output=True, text=True, check=True).stdout


def label(c: Commit) -> tuple[str, str]:
    """(agent, run) a commit is counted under."""
    if c.agent:
        return c.agent, c.run or NO_TRAILER
    if is_owner(c.name, c.email):
        return OWNER, c.run or "-"
    return NO_TRAILER, c.run or NO_TRAILER


def tally(commits: list[Commit]) -> tuple[dict[str, Tally], dict[str, Tally]]:
    by_agent: dict[str, Tally] = defaultdict(Tally)
    by_run: dict[str, Tally] = defaultdict(Tally)
    for c in commits:
        agent, run = label(c)
        for t in (by_agent[agent], by_run[run]):
            t.commits += 1
            t.files |= c.files
            t.tests += c.tests
    return by_agent, by_run


def _table(title: str, key: str, rows: dict[str, Tally]) -> list[str]:
    out = [f"## {title}", "", f"| {key} | Commits | Files | Test definitions added or changed |", "|---|---|---|---|"]
    for k in sorted(rows, key=lambda k: (-rows[k].commits, k)):
        t = rows[k]
        out.append(f"| {k} | {t.commits} | {len(t.files)} | {t.tests} |")
    return out + [""]


def render(commits: list[Commit]) -> str:
    by_agent, by_run = tally(commits)
    files: set[str] = set()
    for c in commits:
        files |= c.files
    out = [
        "# Kiro stats",
        "",
        "Generated by `make kiro-stats` from the `Kiro-Agent` and `Kiro-Run` commit trailers. Merge commits are not counted.",
        f"{len(commits)} commits, {len(files)} distinct files, {sum(c.tests for c in commits)} test definitions added or changed.",
        "",
    ]
    return "\n".join(out + _table("Per agent", "Agent", by_agent) + _table("Per workflow run", "Run", by_run)).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("rev", nargs="?", default="HEAD")
    ap.add_argument("--out")
    args = ap.parse_args(argv)
    text = render(parse(read_log(args.rev)))
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"kiro-stats: wrote {args.out}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
