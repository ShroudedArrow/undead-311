// REQ-OPS-CACHE.1: generate the Netlify `_headers` cache rules for a built site.
//
//   immutable  Vite's hashed build files only: `assets/<name>-<8-character hash>.<ext>` (js, css, fonts, images, maps).
//              A changed file gets a new name, so a year-long immutable cache can never serve stale content.
//   no-cache   `/`, `/index.html`, `/status.json` and everything under `/data/` (the data manifests and shards). The
//              browser keeps a copy but must revalidate it, so a night's refresh shows up at once.
//   nothing    every other file keeps the host's default (revalidate on each visit). A file is never marked
//              immutable unless its name carries a build hash. Check O3 (pipeline/tests/property/test_cache_headers.py).
//
// Compression: Netlify compresses text files on the fly (brotli or gzip, chosen per request), so no precompressed
// `.gz` files are written and none are needed. If a `.gz` or `.br` file is ever present, its name is not a hashed
// asset name, so it is never marked immutable.
//
// Use:  node ops/cache-headers/cache-headers.mjs web/dist      appends or replaces the block in web/dist/_headers
//       node ops/cache-headers/cache-headers.mjs --stdin-json  reads [[file, ...], ...], prints one block per list
// No dependencies: Netlify's build image runs it with the Node version from .nvmrc.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

export const IMMUTABLE = "public, max-age=31536000, immutable";
export const NO_CACHE = "no-cache";
export const BEGIN = "# BEGIN cache-headers (generated by ops/cache-headers/cache-headers.mjs; do not edit)";
export const END = "# END cache-headers";

// The emitted hash: 8 characters of [A-Za-z0-9_-] after a dash, then the extension. At least one digit, capital, `_`
// or `-` is required, so an all-lowercase 8-letter word such as `-gallery.` is never mistaken for a hash.
const HASHED = /^assets\/[^/]+-(?=[A-Za-z0-9_-]{8}\.[A-Za-z0-9]+(?:\.map)?$)(?![a-z]{8}\.)[A-Za-z0-9_-]{8}\.[A-Za-z0-9]+(?:\.map)?$/;
// Characters that make a `_headers` line mean something else (rule separators, placeholders, wildcards, whitespace).
const UNSAFE = /[\s*:]/;

/** @param {string} path a path relative to the publish folder, with `/` separators */
export function isHashedAsset(path) {
  return HASHED.test(path) && !UNSAFE.test(path);
}

/** The block of `_headers` rules for a file list. Deterministic: sorted, deduplicated. */
export function cacheRules(files) {
  const hashed = [...new Set(files.map((f) => f.split(sep).join("/")))].filter(isHashedAsset).sort();
  const rules = [
    ["/", NO_CACHE],
    ["/index.html", NO_CACHE],
    ["/status.json", NO_CACHE],
    ["/data/*", NO_CACHE],
    ...hashed.map((f) => ["/" + f, IMMUTABLE]),
  ];
  const body = rules.map(([path, value]) => `${path}\n  Cache-Control: ${value}`).join("\n");
  return `${BEGIN}\n${body}\n${END}\n`;
}

/** Puts `block` into an existing `_headers` text: replaces a previous generated block, else appends. Idempotent. */
export function applyBlock(existing, block) {
  const start = existing.indexOf(BEGIN);
  const end = existing.indexOf(END);
  if (start !== -1 && end > start) {
    const after = existing.slice(end + END.length).replace(/^\n/, "");
    return existing.slice(0, start) + block + after;
  }
  const base = existing.length === 0 || existing.endsWith("\n") ? existing : existing + "\n";
  return base + (base.length ? "\n" : "") + block;
}

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

function main(argv) {
  if (argv[0] === "--stdin-json") {
    const lists = JSON.parse(readFileSync(0, "utf8"));
    process.stdout.write(JSON.stringify(lists.map(cacheRules)));
    return 0;
  }
  const dist = argv[0];
  if (!dist || !existsSync(dist)) {
    console.error(`cache-headers: publish folder not found: ${dist ?? "(none given)"}`);
    return 1;
  }
  const files = walk(dist).map((p) => relative(dist, p).split(sep).join("/"));
  const target = join(dist, "_headers");
  const existing = existsSync(target) ? readFileSync(target, "utf8") : "";
  writeFileSync(target, applyBlock(existing, cacheRules(files)));
  const n = files.filter(isHashedAsset).length;
  console.log(`cache-headers: ${n} hashed assets immutable; index.html, status.json and data/ no-cache`);
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exit(main(process.argv.slice(2)));
