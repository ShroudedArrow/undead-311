CSP_TS = REPO / "web" / "src" / "lib" / "csp.ts"


def web_csp() -> str:
    """The policy the web build writes into `_headers`, read from its single source `web/src/lib/csp.ts`."""
    text = CSP_TS.read_text()
    body = text[text.index("CSP_DIRECTIVES"):text.index("};")]
    pairs = re.findall(r'"([a-z-]+)":\s*\[([^\]]*)\]', body)
    assert pairs, "csp.ts has no CSP_DIRECTIVES entries"
    return "; ".join(f"{k} " + " ".join(re.findall(r"\"([^\"]+)\"", v)) for k, v in pairs)


def test_the_toml_sets_no_security_header_so_netlify_never_sends_two_policies():
    """REQ-OPS-HOST.3 (ops#59, ops#64): the interim [[headers]] block is gone; the web build's `_headers` is the one policy."""
    assert not config().get("headers")


def test_a_deploy_never_ships_without_a_csp():
    """REQ-OPS-HOST.3 (review N1): the web build writes a same-origin CSP, with no unsafe script source."""
    directives = dict(d.strip().split(" ", 1) for d in web_csp().split(";") if d.strip())
    assert directives["default-src"] == "'self'"
    assert directives["object-src"] == "'none'"
    assert directives["frame-ancestors"] == "'none'"
    assert "'unsafe-eval'" not in web_csp()
    assert "script-src" in directives and "'unsafe-inline'" not in directives["script-src"]


def test_csp_allows_no_outside_host():
    """REQ-OPS-HOST.3, tech.md: no runtime third-party request. No directive names a host, scheme wildcard or `*`."""
    assert not re.search(r"https?:|//|\*|wss?:", web_csp())


def web_build_writes_headers_file() -> bool:
    """True when the web build has a step that writes `_headers`."""
    web = REPO / "web"
    sources = [p for p in [web / "vite.config.ts", *(web / "scripts").glob("*")] if p.is_file()]
    return (web / "public" / "_headers").exists() or any("_headers" in p.read_text() for p in sources)


def test_web_build_writes_the_headers_file():
    """REQ-OPS-HOST.3 (review N1): `_headers` is generated by the web build and the build script runs the writer."""
    assert web_build_writes_headers_file()
    assert "write-headers" in (REPO / "web" / "package.json").read_text()


